// Regenerates common/mandarin/hsk-characters.ts from the vendored HSK 3.0 word lists
// (scripts/mandarin/hsk-new.json, from drkameleon/complete-hsk-vocabulary, MIT).
// Each level lists the Han characters that first appear in that level's words.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = JSON.parse(readFileSync(join(root, 'scripts', 'mandarin', 'hsk-new.json'), 'utf8'));
const seen = new Set();
const levels = Object.keys(source.levels)
    .sort((a, b) => Number(a) - Number(b))
    .map((level) => {
        let chars = '';
        for (const word of source.levels[level]) {
            for (const char of word) {
                if (!/\p{Script=Han}/u.test(char) || seen.has(char)) continue;
                seen.add(char);
                chars += char;
            }
        }
        return chars;
    });
const body = `// Generated by scripts/mandarin/make-hsk-characters.mjs. Do not edit.
// HSK 3.0 characters by the level whose vocabulary first uses them (level 7 covers 7-9).
// Source: ${source.source}
// Copyright (c) Yanis Zafirópulos, MIT License (scripts/mandarin/hsk-new.LICENSE).

export const hskCharacterLevels: readonly string[] = [
${levels.map((chars) => `    '${chars}',`).join('\n')}
];
`;
writeFileSync(join(root, 'common', 'mandarin', 'hsk-characters.ts'), body);
